"""
utils/ctcae_utils.py
────────────────────
CTCAE v6.0 grading + ESC 2022 CTRCD classification for Agentic ChemoTwin.

Source of truth for every threshold in this file:
  - NCI CTCAE v6.0, "CTCAE v6.0 Clean Copy" sheet of
    CTCAE_v6_0_Final_Clean-Tracked-Mapping_w_OS_Jan2026.xlsx
    (machine-readable copy: data/rules/ctcae_v6_terms.json, generated by
    utils/convert_ctcae_excel.py - re-run it if the workbook changes).
  - 2022 ESC Guidelines on cardio-oncology (Lyon et al.), Eur Heart J
    Cardiovasc Imaging 2022;23(10):e333-e465 (co-published in Eur Heart J
    2022;43(41):4229-4361), Table 3 "Cancer therapy-related cardiovascular
    toxicity definitions", p. e347 - verified against the guideline PDF
    (Oct 2026), including footnote c: cTnI/cTnT > 99th percentile,
    BNP >= 35 pg/mL, NT-proBNP >= 125 pg/mL. CTCAE v6.0 adopted the same
    asymptomatic categories as its new term "Left ventricular dysfunction".

REVISION NOTES (knowledge-layer fix, Oct 2026) - what changed and why:
  1. Neutrophil count decreased: previous code used the CTCAE v5.0 bands
     (Grade 4 = ANC < 500). v6.0 shifted every band: G1 <1500-1000,
     G2 <1000-500, G3 <500-100, G4 <100.
  2. Febrile neutropenia: fever now follows the v6.0 wording exactly -
     a SINGLE reading > 38.3 C (strictly greater) OR a SUSTAINED
     temperature >= 38.0 C for MORE than one hour. The old code accepted
     any single reading >= 38.0 C.
  3. Cardiac: "Left ventricular systolic dysfunction" and "Ejection
     fraction decreased" do not exist in CTCAE v6.0. They are replaced by
     "Left ventricular dysfunction" (asymptomatic, new in v6.0) and
     "Heart failure" (symptomatic). Both are implemented below, together
     with the matching ESC 2022 CTRCD categories.
  4. Creatinine increased: the "x baseline" criterion applies ONLY when
     baseline is below LLN (v6.0 wording). The old code applied it to any
     baseline. Grade 4 has no baseline criterion.
  5. Bilirubin / ALT / AST: "x baseline" criteria now apply INSTEAD OF the
     "x ULN" criteria when baseline was > ULN (v6.0 wording), rather than
     being OR-ed with them.
  6. Missing inputs return None (unknown), never 0 (normal). A safety
     system must not report "Grade 0" for a value it never saw.
  7. Reference ranges: the institution's own ULN/LLN are used when present
     (PatientState.lab_reference_ranges, from the hospital annex file);
     otherwise defaults are used and reported in data_quality_flags.
"""

from typing import Any, Dict, List, Optional, Sequence, Tuple

CTCAE_VERSION = "6.0"

# ---------------------------------------------------------------------------
# Reference-range defaults. PLACEHOLDERS until the hospital reference-range
# file arrives; every use of a default is reported in data_quality_flags.
# ---------------------------------------------------------------------------
DEFAULT_REFERENCE_RANGES: Dict[str, Dict[str, float]] = {
    "creatinine": {"lln": 0.5, "uln": 1.2},      # mg/dL
    "total_bilirubin": {"lln": 0.1, "uln": 1.2},  # mg/dL
    "alt": {"lln": 0.0, "uln": 35.0},             # U/L
    "ast": {"lln": 0.0, "uln": 35.0},             # U/L
}
# Backwards-compatible names (imported elsewhere in the codebase)
DEFAULT_ULN_CREATININE = DEFAULT_REFERENCE_RANGES["creatinine"]["uln"]
DEFAULT_ULN_BILIRUBIN = DEFAULT_REFERENCE_RANGES["total_bilirubin"]["uln"]
DEFAULT_ULN_ALT = DEFAULT_REFERENCE_RANGES["alt"]["uln"]
DEFAULT_ULN_AST = DEFAULT_REFERENCE_RANGES["ast"]["uln"]

# CTCAE v6.0 Febrile neutropenia fever criteria
FEVER_SINGLE_READING_C = 38.3        # single reading must be STRICTLY greater
FEVER_SUSTAINED_C = 38.0             # sustained readings must be >= this
FEVER_SUSTAINED_MIN_MINUTES = 60.0   # for MORE than one hour (strictly greater)
FN_ANC_THRESHOLD = 1000.0            # ANC < 1000/mm3

# ESC 2022 CTRCD thresholds (asymptomatic)
GLS_RELATIVE_DECLINE_PCT = 15.0      # "new relative decline in GLS > 15%"
LVEF_POINT_DROP = 10.0               # "LVEF reduction by >= 10 percentage points"
# ESC 2022 / IC-OS biomarker cut-offs. Troponin uses the assay's own
# 99th-percentile URL, which must be supplied with the result.
BNP_THRESHOLD_PG_ML = 35.0
NT_PROBNP_THRESHOLD_PG_ML = 125.0

# CTCAE v6.0 "Heart failure" grades (symptomatic) == ESC symptomatic CTRCD
HEART_FAILURE_STATUS_GRADES: Dict[str, int] = {
    "none": 0,
    "mild_symptoms_no_treatment_change": 1,            # ESC: mild
    "outpatient_treatment_started_or_intensified": 2,  # ESC: moderate
    "hospitalization": 3,                              # ESC: severe
    "inotropes_mcs_or_transplant_consideration": 4,    # ESC: very severe
}
_ESC_SYMPTOMATIC = {0: "none", 1: "mild", 2: "moderate", 3: "severe", 4: "very_severe"}


