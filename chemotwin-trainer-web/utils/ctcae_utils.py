def evaluate_ctcae_renal_grade(
    current_cr: Optional[float],
    baseline_cr: Optional[float] = None,
    uln_cr: float = DEFAULT_ULN_CREATININE,
    lln_cr: float = DEFAULT_REFERENCE_RANGES["creatinine"]["lln"],
) -> Optional[int]:
    """CTCAE v6.0 'Creatinine increased':
      G1 >ULN - 1.5 x ULN
      G2 >1.5 - 3.0 x ULN; or >1.5 - 3.0 x baseline IF baseline is below LLN
      G3 >3.0 - 6.0 x ULN; or >3.0 x baseline IF baseline is below LLN
      G4 >6.0 x ULN
    """
    if current_cr is None or not uln_cr or uln_cr <= 0:
        return None
    fold_uln = current_cr / uln_cr
    use_baseline = baseline_cr is not None and 0 < baseline_cr < lln_cr
    fold_base = (current_cr / baseline_cr) if use_baseline else 0.0

    if fold_uln > 6.0:
        return 4
    if fold_uln > 3.0 or fold_base > 3.0:
        return 3
    if fold_uln > 1.5 or fold_base > 1.5:
        return 2
    if fold_uln > 1.0:
        return 1
    return 0


def _grade_by_multiples(value: float, reference: float, cutoffs: Sequence[float], inclusive_g1: bool) -> int:
    """Grades value/reference against ascending lower bounds for G1..G4."""
    ratio = value / reference
    grade = 0
    for g, lower in enumerate(cutoffs, start=1):
        hit = ratio >= lower if (g == 1 and inclusive_g1) else ratio > lower
        if hit:
            grade = g
    return grade


def grade_bilirubin_increased(value, baseline=None, uln=DEFAULT_ULN_BILIRUBIN) -> Optional[int]:
    """CTCAE v6.0 'Blood bilirubin increased'.
    Baseline normal: G1 >ULN-1.5xULN, G2 >1.5-3.0x, G3 >3.0-10.0x, G4 >10.0x ULN.
    Baseline >ULN:   G1 1.0-1.5x, G2 >1.5-2.5x, G3 >2.5-10.0x, G4 >10.0x baseline."""
    if value is None or not uln or uln <= 0:
        return None
    if baseline is not None and baseline > uln:
        return _grade_by_multiples(value, baseline, (1.0, 1.5, 2.5, 10.0), inclusive_g1=True)
    return _grade_by_multiples(value, uln, (1.0, 1.5, 3.0, 10.0), inclusive_g1=False)


def grade_transaminase_increased(value, baseline=None, uln=DEFAULT_ULN_ALT) -> Optional[int]:
    """CTCAE v6.0 'Alanine/Aspartate aminotransferase increased'.
    Baseline normal: G1 >ULN-3.0xULN, G2 >3.0-5.0x, G3 >5.0-20.0x, G4 >20.0x ULN.
    Baseline >ULN:   G1 1.0-1.5x, G2 >1.5-2.0x, G3 >2.0-4.0x, G4 >4.0x baseline.
    (The v6.0 G3 'up to 5 x ULN' qualifier for abnormal baselines is not modelled.)"""
    if value is None or not uln or uln <= 0:
        return None
    if baseline is not None and baseline > uln:
        return _grade_by_multiples(value, baseline, (1.0, 1.5, 2.0, 4.0), inclusive_g1=True)
    return _grade_by_multiples(value, uln, (1.0, 3.0, 5.0, 20.0), inclusive_g1=False)


def evaluate_ctcae_hepatic_grade(
    total_bilirubin: Optional[float] = None,
    alt_val: Optional[float] = None,
    ast_val: Optional[float] = None,
    baseline_bili: Optional[float] = None,
    baseline_alt: Optional[float] = None,
    baseline_ast: Optional[float] = None,
    uln_bili: float = DEFAULT_ULN_BILIRUBIN,
    uln_alt: float = DEFAULT_ULN_ALT,
    uln_ast: float = DEFAULT_ULN_AST,
) -> Dict[str, Any]:
    bili = grade_bilirubin_increased(total_bilirubin, baseline_bili, uln_bili)
    alt = grade_transaminase_increased(alt_val, baseline_alt, uln_alt)
    ast = grade_transaminase_increased(ast_val, baseline_ast, uln_ast)
    known = [g for g in (bili, alt, ast) if g is not None]
    return {
        "bilirubin_grade": bili,
        "alt_grade": alt,
        "ast_grade": ast,
        "overall_hepatic_ctcae_grade": max(known) if known else None,
    }


