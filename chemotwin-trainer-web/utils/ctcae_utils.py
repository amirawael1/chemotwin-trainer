# Cardiac: CTCAE v6.0 'Left ventricular dysfunction' + 'Heart failure',
# and ESC 2022 CTRCD categories
# ===========================================================================
def gls_relative_decline_pct(baseline_gls: Optional[float], current_gls: Optional[float]) -> Optional[float]:
    """Relative decline in GLS magnitude, in percent (positive = worse).
    GLS is reported as a negative number; e.g. -20 -> -16 is a 20% decline."""
    if baseline_gls is None or current_gls is None or baseline_gls == 0:
        return None
    b, c = abs(baseline_gls), abs(current_gls)
    return (b - c) / b * 100.0


def assess_biomarker_rise(
    troponin: Optional[float] = None,
    troponin_url: Optional[float] = None,
    bnp: Optional[float] = None,
    nt_probnp: Optional[float] = None,
    baseline_troponin: Optional[float] = None,
    baseline_bnp: Optional[float] = None,
    baseline_nt_probnp: Optional[float] = None,
) -> Dict[str, Any]:
    """ESC 2022 'new rise in cardiac biomarkers': troponin > assay 99th
    percentile URL, BNP >= 35 pg/mL, or NT-proBNP >= 125 pg/mL, where the
    value was not already abnormal at baseline (or baseline is unknown).

    NOT implemented: ESC's alternative criterion of a "significant rise from
    baseline beyond biological and analytical variation", which needs
    assay-specific variation data. Returns new_rise=None when nothing was
    measured (unknown, not negative)."""
    checks = []
    if troponin is not None and troponin_url is not None:
        checks.append(("troponin", troponin > troponin_url,
                       baseline_troponin is not None and baseline_troponin > troponin_url))
    if bnp is not None:
        checks.append(("bnp", bnp >= BNP_THRESHOLD_PG_ML,
                       baseline_bnp is not None and baseline_bnp >= BNP_THRESHOLD_PG_ML))
    if nt_probnp is not None:
        checks.append(("nt_probnp", nt_probnp >= NT_PROBNP_THRESHOLD_PG_ML,
                       baseline_nt_probnp is not None and baseline_nt_probnp >= NT_PROBNP_THRESHOLD_PG_ML))
    if not checks:
        return {"new_rise": None, "markers": []}
    risen = [name for name, abnormal_now, abnormal_before in checks if abnormal_now and not abnormal_before]
    return {"new_rise": bool(risen), "markers": risen}


def classify_lv_dysfunction(
    lvef: Optional[float],
    baseline_lvef: Optional[float] = None,
    gls_decline_pct: Optional[float] = None,
    biomarker_new_rise: Optional[bool] = None,
) -> Dict[str, Any]:
    """Asymptomatic cardiac dysfunction, graded two ways:

    CTCAE v6.0 'Left ventricular dysfunction' (verbatim criteria):
      G1: LVEF >= 50% AND (new relative GLS decline > 15% OR new biomarker rise)
      G2: LVEF 40-49% AND (LVEF reduction >= 10% OR GLS decline > 15% OR biomarker rise)
      G3: New LVEF reduction to < 40%
    ESC 2022 asymptomatic CTRCD:
      mild:     LVEF >= 50% AND (GLS decline > 15% and/or new biomarker rise)
      moderate: new LVEF reduction by >= 10 points to 40-49%, OR
                new reduction by < 10 points to 40-49% AND (GLS or biomarkers)
      severe:   new LVEF reduction to < 40%

    The two agree except for one edge case: CTCAE G2 does not require the
    LVEF to have FALLEN when GLS/biomarkers are abnormal, while ESC moderate
    requires a "new reduction". Both are reported so the divergence is
    visible. "LVEF reduction >= 10%" is read as percentage POINTS, matching
    ESC wording.

    'New' (severe/G3) is enforced only when a baseline is known: a patient
    whose baseline was already < 40% is reported as pre-existing, not as
    new CTRCD (Gate 2 still fires on absolute LVEF < 40%)."""
    out: Dict[str, Any] = {
        "ctcae_lv_dysfunction_grade": None,
        "esc_asymptomatic_ctrcd": None,
        "lvef_point_drop": None,
        "gls_decline_pct": gls_decline_pct,
        "gls_criterion_met": None,
        "biomarker_criterion_met": biomarker_new_rise,
        "pre_existing_lvef_below_40": False,
        "notes": [],
    }
    if lvef is None:
        out["notes"].append("LVEF missing - cardiac dysfunction not evaluable.")
        return out

    drop = (baseline_lvef - lvef) if baseline_lvef is not None else None
    out["lvef_point_drop"] = drop
    gls_flag = gls_decline_pct is not None and gls_decline_pct > GLS_RELATIVE_DECLINE_PCT
    out["gls_criterion_met"] = gls_flag if gls_decline_pct is not None else None
    bio_flag = biomarker_new_rise is True
    drop_flag = drop is not None and drop >= LVEF_POINT_DROP

    if lvef < 40.0:
        if baseline_lvef is not None and baseline_lvef < 40.0:
            out["pre_existing_lvef_below_40"] = True
            out["ctcae_lv_dysfunction_grade"] = 0
            out["esc_asymptomatic_ctrcd"] = "none"
            out["notes"].append("LVEF < 40% was already present at baseline (not new CTRCD).")
        else:
            out["ctcae_lv_dysfunction_grade"] = 3
            out["esc_asymptomatic_ctrcd"] = "severe"
            if baseline_lvef is None:
                out["notes"].append("No baseline LVEF: assumed new reduction to < 40%.")
        return out

    if lvef < 50.0:
        ctcae_g2 = drop_flag or gls_flag or bio_flag
        out["ctcae_lv_dysfunction_grade"] = 2 if ctcae_g2 else 0
        esc_moderate = drop_flag or (drop is not None and drop > 0 and (gls_flag or bio_flag))
        out["esc_asymptomatic_ctrcd"] = "moderate" if esc_moderate else "none"
        if drop is None and not (gls_flag or bio_flag):
            out["notes"].append("LVEF 40-49% without baseline LVEF: point drop not evaluable.")
        if ctcae_g2 and not esc_moderate:
            out["notes"].append("CTCAE v6.0 Grade 2 met but ESC 'moderate' not met "
                                "(no documented LVEF fall from baseline).")
        return out

    mild = gls_flag or bio_flag
    out["ctcae_lv_dysfunction_grade"] = 1 if mild else 0
    out["esc_asymptomatic_ctrcd"] = "mild" if mild else "none"
    return out


def grade_heart_failure(status: Optional[str]) -> Optional[int]:
    """CTCAE v6.0 'Heart failure' (symptomatic). `status` is one of the
    HEART_FAILURE_STATUS_GRADES keys; None if not documented."""
    if status is None:
        return None
    if status not in HEART_FAILURE_STATUS_GRADES:
        raise ValueError(f"Unknown heart_failure_status '{status}'. "
                         f"Expected one of {sorted(HEART_FAILURE_STATUS_GRADES)}.")
    return HEART_FAILURE_STATUS_GRADES[status]


def evaluate_ctcae_cardiac_grade(
    lvef_percent: Optional[float] = None,
    minimal_exertion_or_adl_limited: bool = False,
    life_threatening: bool = False,
    baseline_lvef: Optional[float] = None,
    gls_decline_pct: Optional[float] = None,
    biomarker_new_rise: Optional[bool] = None,
) -> Optional[int]:
    """DEPRECATED compatibility shim. The term it used to implement does not
    exist in CTCAE v6.0. Returns the CTCAE v6.0 'Left ventricular
    dysfunction' grade; the two legacy symptom flags are ignored - use
    grade_heart_failure() for symptomatic patients."""
    return classify_lv_dysfunction(
        lvef_percent, baseline_lvef, gls_decline_pct, biomarker_new_rise
    )["ctcae_lv_dysfunction_grade"]


