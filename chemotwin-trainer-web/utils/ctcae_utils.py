def _first_attr(obj: Any, *names: str) -> Any:
    if obj is None:
        return None
    for n in names:
        v = getattr(obj, n, None)
        if v is not None:
            return v
    return None


def _call(obj: Any, method: str) -> Any:
    fn = getattr(obj, method, None)
    return fn() if callable(fn) else None


def get_reference_range(patient_state: Any, test: str, bound: str, flags: List[str]) -> float:
    """Institutional range from PatientState.lab_reference_ranges, then the
    legacy `uln_<test>` attribute, then the default (flagged)."""
    ranges = getattr(patient_state, "lab_reference_ranges", None) or {}
    value = (ranges.get(test) or {}).get(bound)
    if value is None and bound == "uln":
        value = getattr(patient_state, f"uln_{test}", None)
    if value is None:
        value = DEFAULT_REFERENCE_RANGES[test][bound]
        flags.append(f"default_{bound}_used:{test}")
    return value


def _parse_minutes(v: Any) -> Optional[float]:
    """Minutes since midnight from record_time_min or an 'HH:MM' record_time."""
    m = getattr(v, "record_time_min", None)
    if m is not None:
        return float(m)
    t = getattr(v, "record_time", None)
    if isinstance(t, str) and ":" in t:
        hh, mm = t.split(":", 1)
        try:
            return int(hh) * 60 + int(mm[:2])
        except ValueError:
            return None
    return None


def collect_fever_readings(patient_state: Any) -> List[Tuple[Optional[float], Optional[float]]]:
    """All temperature readings recorded on the same relative day as the
    latest vitals record (the current episode)."""
    latest = _call(patient_state, "get_latest_vitals")
    if latest is None:
        return []
    vitals = getattr(patient_state, "vitals", None) or [latest]
    day = getattr(latest, "visit_day", None)
    same_day = [v for v in vitals if getattr(v, "visit_day", None) == day] or [latest]
    return [(_parse_minutes(v), getattr(v, "temperature_c", None)) for v in same_day]


def _baseline_labs(patient_state: Any) -> Any:
    b = _call(patient_state, "get_baseline_labs")
    if b is None:
        labs = getattr(patient_state, "labs", None)
        b = labs[0] if labs else None
    return b


