def grade_neutrophil_count_decreased(anc: Optional[float]) -> Optional[int]:
    """CTCAE v6.0 'Neutrophil count decreased' (cells/mm3 == cells/uL).
    G1 <1500-1000, G2 <1000-500, G3 <500-100, G4 <100. None if unknown."""
    if anc is None:
        return None
    if anc < 100.0:
        return 4
    if anc < 500.0:
        return 3
    if anc < 1000.0:
        return 2
    if anc < 1500.0:
        return 1
    return 0


def assess_fever(readings: Sequence[Tuple[Optional[float], Optional[float]]]) -> Dict[str, Any]:
    """Applies the CTCAE v6.0 febrile-neutropenia fever wording to a set of
    (time_in_minutes, temperature_c) readings from the same episode.

    - single criterion: any reading > 38.3 C
    - sustained criterion: consecutive readings all >= 38.0 C spanning
      MORE than 60 minutes. Requires timestamps; if fewer than two timed
      readings exist, the sustained criterion is reported as not evaluable
      (None) rather than assumed False.
    """
    temps = [t for _, t in readings if t is not None]
    single = any(t > FEVER_SINGLE_READING_C for t in temps)

    timed = sorted((m, t) for m, t in readings if m is not None and t is not None)
    sustained: Optional[bool]
    if len(timed) < 2:
        sustained = None
    else:
        sustained = False
        run_start = None
        for minute, temp in timed:
            if temp >= FEVER_SUSTAINED_C:
                run_start = minute if run_start is None else run_start
                if minute - run_start > FEVER_SUSTAINED_MIN_MINUTES:
                    sustained = True
                    break
            else:
                run_start = None

    if single:
        criterion = "single_reading_gt_38.3C"
    elif sustained:
        criterion = "sustained_ge_38.0C_gt_1h"
    else:
        criterion = None

    return {
        "qualifying_fever": bool(single or sustained),
        "criterion_met": criterion,
        "max_temperature_c": max(temps) if temps else None,
        "sustained_criterion_evaluable": sustained is not None,
    }


def grade_febrile_neutropenia(
    anc: Optional[float],
    fever: Dict[str, Any],
    life_threatening: bool = False,
) -> Optional[int]:
    """CTCAE v6.0 'Febrile neutropenia': Grade 3 = ANC <1000/mm3 with a
    qualifying fever. Grade 4 = life-threatening consequences / urgent
    intervention indicated - a CLINICAL judgement (e.g. septic shock) that
    cannot be derived from ANC and temperature, so it is only assigned when
    explicitly flagged. Grades 1-2 do not exist for this term."""
    if anc is None:
        return None
    if anc < FN_ANC_THRESHOLD and fever.get("qualifying_fever"):
        return 4 if life_threatening else 3
    return 0


def evaluate_ctcae_anc_grade(
    anc_cells_per_ul: Optional[float],
    fever_present: bool = False,
    fever_temp_c: Optional[float] = None,
) -> Dict[str, Any]:
    """Backwards-compatible wrapper (used by tests/test_ctcae.py).
    `fever_present=True` with no temperature is treated as a qualifying
    fever documented elsewhere; with a temperature, the v6.0 single-reading
    rule (> 38.3 C) is applied."""
    if fever_temp_c is not None:
        fever = assess_fever([(None, fever_temp_c)])
    else:
        fever = {"qualifying_fever": bool(fever_present),
                 "criterion_met": "documented_fever" if fever_present else None}
    return {
        "neutrophil_count_grade": grade_neutrophil_count_decreased(anc_cells_per_ul),
        "febrile_neutropenia_grade": grade_febrile_neutropenia(anc_cells_per_ul, fever),
    }


