def evaluate_patient_ctcae_v6(patient_state: Any) -> Dict[str, Any]:
    """Full CTCAE v6.0 + ESC 2022 profile for the current PatientState."""
    flags: List[str] = []
    latest_vitals = _call(patient_state, "get_latest_vitals")
    latest_labs = _call(patient_state, "get_latest_labs")
    baseline_labs = _baseline_labs(patient_state)
    latest_cardiac = _call(patient_state, "get_latest_cardiac")
    baseline_cardiac = _call(patient_state, "get_baseline_cardiac")
    use_base_labs = baseline_labs is not None and baseline_labs is not latest_labs

    # --- Hematologic ---
    anc = _first_attr(latest_labs, "anc_cells_per_ul", "anc")
    fever = assess_fever(collect_fever_readings(patient_state))
    if not fever["sustained_criterion_evaluable"]:
        flags.append("sustained_fever_rule_not_evaluable:no_timed_readings")
    vit_day = getattr(latest_vitals, "visit_day", None)
    lab_day = getattr(latest_labs, "lab_day", None)
    anc_fever_gap = (vit_day - lab_day) if (vit_day is not None and lab_day is not None) else None
    if anc_fever_gap is not None and abs(anc_fever_gap) > 1:
        flags.append(f"anc_temperature_not_contemporaneous:{anc_fever_gap}_days")
    fn_life_threatening = bool(getattr(patient_state, "fn_life_threatening", False))

    # --- Cardiac ---
    lvef = _first_attr(latest_cardiac, "ejection_fraction_pct")
    base_lvef = (_first_attr(baseline_cardiac, "ejection_fraction_pct")
                 if baseline_cardiac is not None and baseline_cardiac is not latest_cardiac else None)
    gls_decline = _call(patient_state, "compute_gls_relative_change")
    if gls_decline is None and baseline_cardiac is not latest_cardiac:
        gls_decline = gls_relative_decline_pct(
            _first_attr(baseline_cardiac, "global_longitudinal_strain_pct"),
            _first_attr(latest_cardiac, "global_longitudinal_strain_pct"),
        )
    bio = assess_biomarker_rise(
        troponin=_first_attr(latest_labs, "troponin_ng_l"),
        troponin_url=_first_attr(latest_labs, "troponin_url_ng_l"),
        bnp=_first_attr(latest_labs, "bnp_pg_ml"),
        nt_probnp=_first_attr(latest_labs, "nt_probnp_pg_ml"),
        baseline_troponin=_first_attr(baseline_labs, "troponin_ng_l") if use_base_labs else None,
        baseline_bnp=_first_attr(baseline_labs, "bnp_pg_ml") if use_base_labs else None,
        baseline_nt_probnp=_first_attr(baseline_labs, "nt_probnp_pg_ml") if use_base_labs else None,
    )
    lv = classify_lv_dysfunction(lvef, base_lvef, gls_decline, bio["new_rise"])
    hf_grade = grade_heart_failure(getattr(patient_state, "heart_failure_status", None))

    # --- Renal ---
    cr = _first_attr(latest_labs, "creatinine_mg_dl", "creatinine")
    base_cr = _first_attr(baseline_labs, "creatinine_mg_dl", "creatinine") if use_base_labs else None
    uln_cr = get_reference_range(patient_state, "creatinine", "uln", flags)
    lln_cr = get_reference_range(patient_state, "creatinine", "lln", flags)
    renal = evaluate_ctcae_renal_grade(cr, base_cr, uln_cr, lln_cr)

    # --- Hepatic ---
    hepatic = evaluate_ctcae_hepatic_grade(
        total_bilirubin=_first_attr(latest_labs, "total_bilirubin_mg_dl", "total_bilirubin"),
        alt_val=_first_attr(latest_labs, "alt_u_l", "alt"),
        ast_val=_first_attr(latest_labs, "ast_u_l", "ast"),
        baseline_bili=_first_attr(baseline_labs, "total_bilirubin_mg_dl", "total_bilirubin") if use_base_labs else None,
        baseline_alt=_first_attr(baseline_labs, "alt_u_l", "alt") if use_base_labs else None,
        baseline_ast=_first_attr(baseline_labs, "ast_u_l", "ast") if use_base_labs else None,
        uln_bili=get_reference_range(patient_state, "total_bilirubin", "uln", flags),
        uln_alt=get_reference_range(patient_state, "alt", "uln", flags),
        uln_ast=get_reference_range(patient_state, "ast", "uln", flags),
    )

    lv_grade = lv["ctcae_lv_dysfunction_grade"]
    known_cardiac = [g for g in (lv_grade, hf_grade) if g is not None]

    return {
        "ctcae_version": CTCAE_VERSION,
        # Hematologic
        "neutrophil_count_grade": grade_neutrophil_count_decreased(anc),
        "febrile_neutropenia_grade": grade_febrile_neutropenia(anc, fever, fn_life_threatening),
        "fever_assessment": fever,
        "anc_temperature_day_gap": anc_fever_gap,
        # Cardiac
        "lv_dysfunction_grade": lv_grade,
        "heart_failure_grade": hf_grade,
        "esc_ctrcd": {
            "asymptomatic": lv["esc_asymptomatic_ctrcd"],
            "symptomatic": _ESC_SYMPTOMATIC.get(hf_grade) if hf_grade is not None else None,
            "lvef_point_drop": lv["lvef_point_drop"],
            "gls_decline_pct": lv["gls_decline_pct"],
            "gls_criterion_met": lv["gls_criterion_met"],
            "biomarker_criterion_met": lv["biomarker_criterion_met"],
            "biomarkers_risen": bio["markers"],
            "pre_existing_lvef_below_40": lv["pre_existing_lvef_below_40"],
            "notes": lv["notes"],
        },
        # DEPRECATED alias kept so older callers do not break; prefer the two
        # specific keys above. Max of LV dysfunction and heart failure grades.
        "cardiac_disorder_grade": max(known_cardiac) if known_cardiac else None,
        # Renal / hepatic
        "creatinine_increased_grade": renal,
        "bilirubin_increased_grade": hepatic["bilirubin_grade"],
        "alt_increased_grade": hepatic["alt_grade"],
        "ast_increased_grade": hepatic["ast_grade"],
        "overall_hepatic_ctcae_grade": hepatic["overall_hepatic_ctcae_grade"],
        "data_quality_flags": sorted(set(flags)),
    }